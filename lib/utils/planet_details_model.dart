class PlanetDetailsModel {
  String title;
  String about;
  String distance;
  String lengthOfDay;
  String orbitalPeriod;
  String radius;
  String mass;
  String gravity;
  String surfaceArea;
  String imagePath;

  PlanetDetailsModel({
    required this.title,
    required this.about,
    required this.distance,
    required this.gravity,
    required this.lengthOfDay,
    required this.mass,
    required this.orbitalPeriod,
    required this.radius,
    required this.surfaceArea,
    required this.imagePath
  });
}
